"""Собирает MEAN_REVERSION_CHECK.md из MEAN_REVERSION_CHECK.json. Руками .md не правится."""
import json
from pathlib import Path

d = Path(__file__).resolve().parent
r = json.loads((d / "MEAN_REVERSION_CHECK.json").read_text(encoding="utf-8"))
L = []
A = L.append

A("# Возврат к среднему на BTCUSDT Spot: проверка и отзыв результата\n")
A("Отчёт собран автоматически из `MEAN_REVERSION_CHECK.json`, который пишет "
  "`mean_reversion_check.py`. Руками не правится.\n")
A("## Воспроизведение\n")
A("```\ncd research_mean_reversion\npython mean_reversion_check.py   # -> MEAN_REVERSION_CHECK.json")
A("python render_report.py          # -> MEAN_REVERSION_CHECK.md\n```\n")
A("| параметр | значение |\n|---|---|")
A("| seed | `%d` |" % r["seed"])
A("| суррогатных прогонов на горизонт | %d |" % r["surrogate_draws"])
A("| Python / numpy | %s / %s |" % (r["python"], r["numpy"]))
A("\n**Входные данные** — набор `DATA_BTCUSDT_SPOT_6M`, Bybit Spot BTCUSDT, 2026-03-01 … 2026-09-01:\n")
A("| ТФ | файл | SHA-256 |\n|---|---|---|")
for tf, m in r["inputs"].items():
    A("| %s | `%s` | `%s` |" % (tf, m["file"], m["sha256"]))

A("\n## Что проверялось\n")
A("Тест отношения дисперсий Ло–Маккинлея: `VR(q) < 1` означает, что дисперсия "
  "`q`-барной доходности меньше, чем `q` дисперсий однобарной, то есть ряд возвращается к среднему.\n")
A("Значимость считается двумя способами. **M1** предполагает постоянную дисперсию. "
  "**M2** устойчив к кластеризации волатильности. У BTC избыточный эксцесс измеряется "
  "десятками, поэтому предпосылка M1 нарушена и его `z` завышен.\n")
A("Дополнительно два суррогата:\n")
A("- **перемешивание** — рушит и порядок доходностей, и кластеризацию волатильности, "
  "поэтому различить их причины не может;")
A("- **рандомизация знака** — оставляет `|r_t|` на своих местах, то есть сохраняет "
  "кластеризацию волатильности и тяжёлые хвосты целиком, и убивает только направленную "
  "зависимость. Это и есть решающая проверка.\n")

for tf, b in r["timeframes"].items():
    A("## %s — %d бар, избыточный эксцесс %.1f\n" % (tf, b["bars"], b["excess_kurtosis"]))
    A("| q | VR | z (M1) | z (**M2**) | перемешивание | рандомизация знака | перцентиль |")
    A("|---|---|---|---|---|---|---|")
    for q, v in b["q"].items():
        A("| %s | %.4f | %+.2f | **%+.2f** | %s | %s | %.1f%% |" % (
            q, v["vr"], v["z_homoskedastic"], v["z_robust_M2"],
            "вне полосы" if v["shuffle_outside"] else "внутри",
            "**вне полосы**" if v["signflip_outside"] else "внутри",
            v["signflip_pctile"]))
    surv = sum(1 for v in b["q"].values() if v["signflip_outside"])
    A("\nПереживает рандомизацию знака: **%d из %d** горизонтов. "
      "Максимальный по модулю робастный z: **%+.2f**.\n" % (
          surv, len(b["q"]), min(v["z_robust_M2"] for v in b["q"].values())))
    A("Устойчивость по 6 равным подпериодам, q=64:\n")
    A("| блок | " + " | ".join(str(x["block"]) for x in b["subperiods_q64"]) + " |")
    A("|---|" + "---|" * len(b["subperiods_q64"]))
    A("| VR | " + " | ".join("%.3f" % x["vr"] for x in b["subperiods_q64"]) + " |")
    A("| z (M2) | " + " | ".join("%+.2f" % x["z_robust_M2"] for x in b["subperiods_q64"]) + " |")
    vs = [x["vr"] for x in b["subperiods_q64"]]
    A("\nЗнак эффекта меняется между подпериодами: **%s**. "
      "Ни один подпериод не значим по отдельности (max |z| = %.2f).\n" % (
          "да" if min(vs) < 1 < max(vs) else "нет",
          max(abs(x["z_robust_M2"]) for x in b["subperiods_q64"])))

A("## Buy-and-hold за тот же период\n")
A("| ТФ | результат |\n|---|---|")
for tf, b in r["timeframes"].items():
    A("| %s | %+.2f%% |" % (tf, b["buy_and_hold_pct"]))
A("\nСовпадение по трём таймфреймам — внутренняя проверка согласованности данных.\n")

A("## Вывод\n")
A("1. `VR < 1` присутствует на всех трёх таймфреймах, то есть сырой эффект есть.")
A("2. **Гомоскедастичная статистика завышает значимость примерно вдвое.** "
  "На 1m при q=8: z(M1) = %+.2f против z(M2) = %+.2f. Причина — избыточный эксцесс до %.1f."
  % (r["timeframes"]["1m"]["q"]["8"]["z_homoskedastic"],
     r["timeframes"]["1m"]["q"]["8"]["z_robust_M2"],
     max(b["excess_kurtosis"] for b in r["timeframes"].values())))
A("3. После рандомизации знака эффект **частично выживает на 1m** (%d из 8 горизонтов, "
  "перцентиль 1–3%%), почти исчезает на 5m (%d из 8) и исчезает на 15m (%d из 8)."
  % tuple(sum(1 for v in r["timeframes"][tf]["q"].values() if v["signflip_outside"])
          for tf in ("1m", "5m", "15m")))
A("4. По подпериодам ни на одном таймфрейме нет ни одного значимого блока, "
  "а на 5m и 15m знак эффекта разворачивается.")
A("5. Простого перемешивания для этой проверки **недостаточно**: оно отвергает нулевую "
  "гипотезу почти везде, потому что заодно убивает кластеризацию волатильности.\n")
A("**Что из этого следует.** Утверждение «возврат к среднему статистически значим», "
  "основанное на гомоскедастичном z, не подтверждается. Остаточный эффект на 1m "
  "находится на границе условной значимости и не воспроизводится на более длинных "
  "таймфреймах и внутри подпериодов. Как основание для торговой стратегии этого "
  "недостаточно; величина эффекта в этом отчёте не измерялась.\n")

(d / "MEAN_REVERSION_CHECK.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("MEAN_REVERSION_CHECK.md записан, %d строк" % len(L))
